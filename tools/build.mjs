import { build } from 'esbuild';
import { chmodSync, cpSync, rmSync, copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
rmSync('factory/template/examples',{recursive:true,force:true});
cpSync('packages/engine/examples','factory/template/examples',{recursive:true});
mkdirSync('factory/template/.codex',{recursive:true});
copyFileSync('factory/designer/AGENTS.md','factory/template/AGENTS.md');
copyFileSync('factory/designer/.codex/config.toml','factory/template/.codex/config.toml');
const tool='factory/template/tools/playtest.mjs';
mkdirSync('factory/template/tools',{recursive:true});
mkdirSync('factory/template/spec',{recursive:true});
if(existsSync(tool))chmodSync(tool,0o644);
await build({
 entryPoints:['packages/harness/src/cli.ts'],
 outfile:tool,
 bundle:true,platform:'node',format:'esm',target:'node22',
 banner:{js:'// Generated by npm run build. Edit packages/harness and rebuild.\n// Runtime factory agents must treat this tool as read only.'},
 minify:true, legalComments:'inline'
});
chmodSync(tool,0o444);
for(const file of ['SPEC.md','schema.json'])copyFileSync('packages/engine/'+file,'factory/template/spec/'+file);
const licenses=[
 ['ajv','LICENSE'],['fast-deep-equal','LICENSE'],['fast-uri','LICENSE'],
 ['json-schema-traverse','LICENSE'],['require-from-string','license']
];
writeFileSync('factory/template/tools/LICENSES.txt',
 'Bundled dependency licenses\n\n'+licenses.map(([name,file])=>name+'\n\n'+readFileSync('node_modules/'+name+'/'+file,'utf8')).join('\n\n'));
console.log('Built self contained factory playtest and synced format docs.');
await build({
 entryPoints:['packages/twitch/src/index.ts'],outfile:'dist/twitch-mock.mjs',
 bundle:true,packages:'external',platform:'node',format:'esm',target:'node22'
});

await build({
 entryPoints:['apps/server/src/factory-check.ts'],outfile:'dist/factory-check.mjs',
 bundle:true,packages:'external',platform:'node',format:'esm',target:'node22'
});
await build({
 entryPoints:['apps/server/src/validator.ts'],outfile:'dist/validator.mjs',
 bundle:true,packages:'external',platform:'node',format:'esm',target:'node22'
});
for(const [entry,outfile] of [['main','server'],['demo-check','demo-check'],['forget','forget']]){
 await build({
  entryPoints:['apps/server/src/'+entry+'.ts'],outfile:'dist/'+outfile+'.mjs',
  bundle:true,packages:'external',platform:'node',format:'esm',target:'node22'
 });
}
